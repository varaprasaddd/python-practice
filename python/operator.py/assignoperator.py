#assign operators
a = 5
a += 3  # a = a + 3
print("After += operator, a =", a)

# Subtraction assignment operator
b = 10
b -= 4  # b = b - 4 
print("After -= operator, b =", b)

# Multiplication assignment operator
c = 6
c *= 2  # c = c * 2
print("After *= operator, c =", c)

# Division assignment operator
d = 20
d /= 5  # d = d / 5
print("After /= operator, d =", d)

# Modulus assignment operator
e = 15
e %= 4  # e = e % 4
print("After %= operator, e =", e)

# Floor division assignment operator
f = 9
f //= 2  # f = f // 2
print("After //= operator, f =", f)

# Exponentiation assignment operator
g = 3
g **= 3  # g = g ** 3
print("After **= operator, g =", g)

# Bitwise AND assignment operator
h = 8
h &= 5  # h = h & 5
print("After &= operator, h =", h)

# OR assignment operator
i = 12
i |= 7  # i = i | 7
print("After |= operator, i =", i)

# XOR assignment operator
j = 14
j ^= 3  # j = j ^ 3
print("After ^= operator, j =", j)

# Right shift assignment operator
k = 20
k >>= 2  # k = k >> 2
print("After >>= operator, k =", k)

# Left shift assignment operator
l = 16
l <<= 1  # l = l << 1
print("After <<= operator, l =", l)